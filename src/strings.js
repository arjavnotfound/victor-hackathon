// Lines with a number or a name inside them.
const PATTERNS = [
  [/^(\d+) things? worth a closer look\.$/, '$1 चीज़ें ध्यान से देखने लायक।'],
  [/^(\d+) (?:spots?|items?|devices?) worth a closer look$/, '$1 ध्यान से देखने लायक'],
  [/^(\d+) worth a closer look$/, '$1 ध्यान से देखने लायक'],
  [/^Wi-Fi chip made by (.+), common in small cameras$/, 'Wi-Fi chip $1 का है, जो छोटे camera में आम है'],
  [/^(\d+) scans?$/, '$1 स्कैन'],
  [/^(\d+) of 12$/, '12 में से $1'],
];

/** Language chosen on this phone ('en' or 'hi'). */
export function getLang() {
  try { return localStorage.getItem('victor.lang') === 'hi' ? 'hi' : 'en'; } catch { return 'en'; }
}
export function setLang(lang) {
  try { localStorage.setItem('victor.lang', lang); } catch { /* storage blocked */ }
}

/** Hindi for one English line, or the line itself. */
export function tr(text, lang = getLang()) {
  if (lang !== 'hi') return null;
  const t = text.trim();
  if (hi[t]) return hi[t];
  for (const [re, out] of PATTERNS) if (re.test(t)) return t.replace(re, out);
  return null;
}
